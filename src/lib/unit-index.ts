import fs from "node:fs";
import path from "node:path";
import { asStrings, BUCKETS, parseFrontmatter, type Bucket } from "./frontmatter";

export type UnitIndexEntry = {
  id: string;
  title: string;
  bucket: Bucket;
  version: number;
  status: string;
  owner: string;
  entities: string[];
  supersedes: string | null;
  path: string;
};

export function collectUnits(root: string): UnitIndexEntry[] {
  const entries: UnitIndexEntry[] = [];
  for (const bucket of BUCKETS) {
    const bucketDir = path.join(root, "units", bucket);
    if (!fs.existsSync(bucketDir)) continue;
    for (const id of fs.readdirSync(bucketDir)) {
      const file = path.join(bucketDir, id, "UNIT.md");
      if (!fs.existsSync(file)) continue;
      const { data } = parseFrontmatter(fs.readFileSync(file, "utf8"));
      entries.push({
        id: String(data.id),
        title: String(data.title),
        bucket: data.bucket as Bucket,
        version: Number(data.version),
        status: String(data.status),
        owner: String(data.owner),
        entities: asStrings(data.entities, "entities"),
        supersedes: typeof data.supersedes === "string" ? data.supersedes : null,
        path: path.posix.join("units", bucket, id, "UNIT.md"),
      });
    }
  }
  return entries.sort(
    (left, right) => BUCKETS.indexOf(left.bucket) - BUCKETS.indexOf(right.bucket) || left.id.localeCompare(right.id),
  );
}

export function writeUnitIndex(root: string): UnitIndexEntry[] {
  const units = collectUnits(root);
  const payload = {
    note: "Generated by scripts/build-unit-index.ts. Do not edit by hand.",
    units,
  };
  fs.mkdirSync(path.join(root, "units"), { recursive: true });
  fs.writeFileSync(path.join(root, "units/index.json"), `${JSON.stringify(payload, null, 2)}\n`);
  return units;
}

export function readUnitIndex(root = process.cwd()): UnitIndexEntry[] {
  const file = path.join(root, "units/index.json");
  if (!fs.existsSync(file)) {
    throw new Error("units/index.json is missing. Run npm run build-unit-index.");
  }
  const parsed = JSON.parse(fs.readFileSync(file, "utf8")) as { units: UnitIndexEntry[] };
  return parsed.units;
}
