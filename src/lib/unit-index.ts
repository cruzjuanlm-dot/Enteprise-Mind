export function collectUnits(root: string): UnitIndexEntry[] {
  const entries: UnitIndexEntry[] = [];
  const projectsRoot = path.join(root, "projects");
  if (!fs.existsSync(projectsRoot)) return entries;
  for (const projectDir of fs.readdirSync(projectsRoot, { withFileTypes: true })) {
    if (!projectDir.isDirectory() || projectDir.name === "_template") continue;
    const unitsDir = path.join(projectsRoot, projectDir.name, "units");
    if (!fs.existsSync(unitsDir)) continue;
    for (const name of fs.readdirSync(unitsDir)) {
      if (!name.endsWith(".md")) continue;
      const absolute = path.join(unitsDir, name);
      if (!fs.statSync(absolute).isFile()) continue;
      const { data } = parseFrontmatter(fs.readFileSync(absolute, "utf8"));
      const id = String(data.id);
      const parsed = parseUnitId(id);
      entries.push({
        id,
        title: String(data.title),
        type: (parsed?.type ?? data.type) as TypeCode,
        scope: data.scope as UnitScope,
        project: String(data.project),
        sourceId: String(data.source_id),
        version: Number(data.version),
        status: String(data.status),
        owner: String(data.owner),
        entities: asStrings(data.entities, "entities"),
        supersedes: typeof data.supersedes === "string" ? data.supersedes : null,
        path: path.posix.join("projects", projectDir.name, "units", name),
        domain: asDomain(data.domain),
        subType: asOptionalString(data.sub_type),
        meeting: asOptionalString(data.meeting),
        meetingDate: asOptionalString(data.meeting_date),
        systemsTouched: asStringList(data.systems_touched),
        acceptanceCriteria: asOptionalString(data.acceptance_criteria),
      });
    }
  }
  return entries.sort((left, right) => left.id.localeCompare(right.id) || TYPE_CODES.indexOf(left.type) - TYPE_CODES.indexOf(right.type));
}

export function renderRoutingIndex(units: UnitIndexEntry[]): string {
  const projects = [...new Set(units.map((unit) => unit.project))].sort();
  const lines = [
    "# Index",
    "",
    "Generated by scripts/build-unit-index.ts. Routing only. Do not edit by hand.",
    "",
    "A knowledge unit stays in `projects/{id}/units/`. Company scope is `scope: company` plus `domain` in the file. The file does not move.",
    "",
    "| Route | What belongs here |",
    "| --- | --- |",
    ...ROUTES.map(([route, what]) => `| \`${route}\` | ${what} |`),
    "",
    "## Project routes",
    "",
    ...(projects.length === 0
      ? ["No project units yet.", ""]
      : projects.flatMap((projectId) => [`- \`projects/${projectSlug(projectId)}/units/\` — ${projectId}`, ""])),
    "## Company routes",
    "",
    "Company-scoped units stay in the project file. `domain` projects them onto a core route.",
    "",
    ...DOMAINS.flatMap((domain) => {
      const routed = units.filter((unit) => unit.scope === "company" && unit.domain === domain);
      const route = DOMAIN_ROUTE[domain];
      if (routed.length === 0) return [`- \`${route}\` — no company units`, ""];
      return [`- \`${route}\``, ...routed.map((unit) => `  - \`${unit.id}\` → \`${unit.path}\``), ""];
    }),
    "## Unit routes",
    "",
    ...(units.length === 0 ? ["No units yet."] : units.map((unit) => `- \`${unit.id}\` → \`${unit.path}\``)),
    "",
  ];
  return lines.join("\n");
}

export function writeUnitIndex(root: string): UnitIndexEntry[] {
  const units = collectUnits(root);
  const payload = {
    note: "Generated by scripts/build-unit-index.ts. Do not edit by hand.",
    units,
  };
  const ledger = path.join(root, LEDGER);
  fs.mkdirSync(path.dirname(ledger), { recursive: true });
  fs.writeFileSync(ledger, `${JSON.stringify(payload, null, 2)}\n`);
  fs.writeFileSync(path.join(root, "INDEX.md"), renderRoutingIndex(units));
  return units;
}

export function readUnitIndex(root = process.cwd()): UnitIndexEntry[] {
  const file = path.join(root, LEDGER);
  if (!fs.existsSync(file)) {
    throw new Error(`${LEDGER} is missing. Run npm run build-unit-index.`);
  }
  const parsed = JSON.parse(fs.readFileSync(file, "utf8")) as { units: UnitIndexEntry[] };
  return parsed.units;
}
